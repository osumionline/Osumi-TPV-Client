/**
 * Número de puntos básicos contenidos
 * en un punto porcentual.
 */
export const BASIS_POINTS_PER_PERCENT: number = 100;

/**
 * Porcentaje que representa el total.
 */
export const PERCENT_TOTAL: number = 100;

/**
 * Número de puntos básicos que representa
 * el 100 %.
 */
export const BASIS_POINTS_TOTAL: number = PERCENT_TOTAL * BASIS_POINTS_PER_PERCENT;
